-- Player shots for the lot portrait band.
--
-- Kept in its own table rather than on player_weeks: a headshot is a fact about
-- a player, not about a player-week, and the pool carries roughly fifty weeks
-- per player. One row each keeps this migration small and makes a refresh a
-- replace rather than a rewrite of the whole pool.
--
-- WHY `private`, when the images themselves are public: the pool is private so
-- that a client cannot enumerate what might be dealt. A public headshot table
-- would hand over the same 810-name list by another route. The lot copies the
-- URL it needs at deal time, exactly as it already copies the card-visible
-- fields off player_weeks.
--
-- The identity carried across from nflverse is the GSIS id, which is the
-- player_id the pool is already keyed on -- so no name join, and a later pool
-- rebuild maps to these rows for free. The URL is stored whole because
-- nflverse serves two Cloudinary path forms (/image/private/ and
-- /image/upload/) and reconstructing one from an asset id would guess wrong on
-- roughly four rows in ten.

create table private.player_headshots (
  player_id    text primary key,
  headshot_url text not null
);

-- Copied onto the lot at deal time, alongside the other card-visible fields.
alter table public.auction_lots add column headshot_url text;

